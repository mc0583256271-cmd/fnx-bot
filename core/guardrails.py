"""
שלב 5: שאלות גבול שמטופלות לפני החיפוש.

- הודעות שיחה (תודה, שלום, ביי...) - תשובה ידידותית מיד, בלי חיפוש ובלי מודל.
- בקשה לפרט אישי (מספר הפוליסה שלי, מה מצב התביעה שלי, כמה כסף יש לי) - הסבר שאין לבוט
  גישה לפרטים אישיים והפניה לשירות הלקוחות. בלי חיפוש ובלי מודל.
(שאלה כללית על כיסוי, כמו "האם הפוליסה שלי מכסה נזקי מים", ממשיכה לחיפוש - ההוראות למודל
 אומרות להסביר מה כתוב באתר ולהפנות לשירות הלקוחות לבדיקת הפוליסה האישית.)
"""
import re

_WORDS = r"(תודה|תודה רבה|רבה|תנקס|שלום|היי|הי|הלו|בוקר טוב|ערב טוב|לילה טוב|צהריים טובים|ביי|להתראות|יום טוב|" \
         r"מעולה|מצוין|אחלה|סבבה|אוקיי|אוקי|אוקיי תודה|הבנתי|ברור|נהדר|יופי|יפה|מגניב|נחמד|וואו|כל הכבוד|ok|thanks|thank you|hi|hello|bye)"
_SMALL_TALK = re.compile(rf"^\s*({_WORDS}[\s,!.?:)(]*)+$", re.IGNORECASE)

THANKS = "בשמחה! אם יש עוד שאלה על ביטוח, תביעות, פנסיה או חיסכון - אני כאן."
GREETING = "שלום! אפשר לשאול אותי על ביטוח, תביעות, פנסיה, חיסכון והלוואות - אענה לפי המידע באתר הפניקס."
BYE = "להתראות! אם תצטרכו עוד משהו, אני כאן."


def small_talk_reply(message):
    """אם ההודעה היא רק נימוס/ברכה - מחזיר תשובה מתאימה. אחרת None (ממשיכים לחיפוש)."""
    text = message.strip()
    if len(text) > 40 or not _SMALL_TALK.match(text):
        return None
    if re.search(r"ביי|להתראות|לילה טוב|bye", text, re.IGNORECASE):
        return BYE
    if re.search(r"שלום|היי|הי|הלו|בוקר טוב|ערב טוב|צהריים טובים|hi|hello", text, re.IGNORECASE) \
            and not re.search(r"תודה|thank", text, re.IGNORECASE):
        return GREETING
    return THANKS


_PERSONAL = re.compile(
    r"(מספר|מס'|מס׳)\s*(ה)?(פוליסה|חשבון|תביעה|לקוח)\s*(שלי|שלנו)"
    r"|(ה)?(תביעה|בקשה|פנייה)\s*(שלי|ששלחתי|שהגשתי)\s*.{0,25}(אושר|נדח|טופל|התקבל|מצב|סטטוס|איפה|מתי)"
    r"|(מצב|סטטוס)\s*(ה)?(תביעה|בקשה|פנייה)\s*(שלי|ששלחתי|שהגשתי)"
    r"|כמה\s*(כסף|יש לי|צברתי|הצטבר)\s*.{0,20}(שלי|לי|בקרן|בקופה|בפנסיה|בחיסכון)"
    r"|(היתרה|הצבירה|הפרטים|החשבון|התשלומים)\s*(שלי)"
    r"|כמה\s*(אני\s*)?(מקבל|מקבלת|אקבל|יש לי)\s*(על|מ|ב)?\s*(ה)?(פוליסה|חשבון|קופה|קרן|חיסכון)\s*(שלי)"
)
PERSONAL = ("אין לי גישה לפרטים אישיים - פוליסה, תביעה או חשבון. "
            "את הפרטים שלך אפשר לבדוק מול שירות הלקוחות. "
            "אשמח לעזור בשאלות כלליות לפי המידע באתר, למשל מה כולל כיסוי מסוים או איך מגישים תביעה.")


def personal_reply(message):
    """אם ההודעה מבקשת פרט אישי שאין לבוט גישה אליו - מחזיר הסבר. אחרת None."""
    return PERSONAL if _PERSONAL.search(message) else None


_ABOUT = re.compile(
    r"(מה|איך)\s*(ה)?שם\s*(שלך|שלכם)|איך קוראים (לך|לכם)|מי (אתה|את)\b|את(ה)? (בוט|רובוט|בן אדם|אדם|אמיתי)"
    r"|מי (כתב|בנה|פיתח|תכנת|יצר)|שאלות אישיות|מה (אתה|את) (יודע|יודעת|יכול|יכולה)|על מה (אפשר|אני יכול) לשאול")
ABOUT = ("אני העוזר הדיגיטלי של הפניקס - בוט שעונה על שאלות לפי המידע שבאתר fnx.co.il, ומצרף לכל תשובה "
         "את העמוד שממנו היא נלקחה. אפשר לשאול אותי על ביטוח, תביעות, פנסיה וחיסכון. "
         "אין לי גישה לפרטים אישיים כמו פוליסה או תביעה - אותם בודקים בשירות הלקוחות. על מה תרצו לשאול?")


def about_reply(message):
    """שאלה על הבוט עצמו ("מה השם שלך", "מי כתב אותך") - הסבר קצר מי הוא ומה אפשר לשאול."""
    return ABOUT if len(message) < 80 and _ABOUT.search(message) else None
